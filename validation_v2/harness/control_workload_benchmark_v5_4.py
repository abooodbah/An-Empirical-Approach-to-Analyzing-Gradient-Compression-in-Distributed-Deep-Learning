def validate_v52(args: argparse.Namespace) -> None:
    bucketed = args.comm_mode in BUCKETED_MODES
    if bucketed and args.exchange_bucket_elems < 1:
        raise ConfigurationError(f"{args.comm_mode} requires --exchange-bucket-elems")
    if not bucketed and args.exchange_bucket_elems:
        raise ConfigurationError("--exchange-bucket-elems applies to the bucketed modes only")
    if args.progress_dir is not None and args.timing_mode == "block":
        raise ConfigurationError("--progress-dir would write inside a block-timed block")
    if args.verify_fidelity and args.profile != "qualification":
        raise ConfigurationError("--verify-fidelity is for qualification runs only")
    if args.verify_fidelity and args.comm_mode in DDP_MODES:
        raise ConfigurationError("--verify-fidelity needs the gradient before the exchange; DDP modes hide it")
    if args.comm_mode in STOCHASTIC_MODES and args.profile == "paper":
        raise ConfigurationError("the stochastic quantizers are not paper-profile conditions")


def validate_config(args: argparse.Namespace) -> argparse.Namespace:
    if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9._-]{0,127}", args.campaign_id):
        raise ConfigurationError(
            "--campaign-id must be 1-128 characters using only letters, digits, dot, underscore, or hyphen"
        )
    if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9._-]{0,127}", args.run_id):
        raise ConfigurationError(
            "--run-id must be 1-128 characters using only letters, digits, dot, underscore, or hyphen"
        )
    if args.calibration_reference is not None and not re.fullmatch(
        r"[A-Za-z0-9][A-Za-z0-9._-]{0,127}", args.calibration_reference
    ):
        raise ConfigurationError(
            "--calibration-reference must be 1-128 characters using only letters, digits, "
            "dot, underscore, or hyphen"
        )
    if args.calibration_reference is not None and not args.skip_calibration:
        raise ConfigurationError("--calibration-reference requires --skip-calibration")
    if args.profile == "paper" and args.skip_calibration and args.calibration_reference is None:
        raise ConfigurationError(
            "paper-profile --skip-calibration requires --calibration-reference"
        )
    if args.batch_size < 1 or args.iters < 1 or args.warmup_iters < 0:
        raise ConfigurationError("batch size and measured iterations must be positive; warmup cannot be negative")
    if args.sync_every not in PAPER_SYNC_VALUES:
        raise ConfigurationError(f"--sync-every must be one of {PAPER_SYNC_VALUES}")
    if args.comm_mode not in ("native", "gpu-topk", "fp16-native") and args.sync_every != 1:
        raise ConfigurationError(
            f"{args.comm_mode} is a static paper condition and therefore requires --sync-every 1"
        )
    if not (0.0 < args.topk_frac <= 1.0):
        raise ConfigurationError("--topk-frac must be in (0, 1]")
    if args.powersgd_rank < 1 or args.powersgd_start < 1:
        raise ConfigurationError("PowerSGD rank and start iteration must be positive")
    if (args.powersgd_error_feedback or args.powersgd_warm_start) and args.powersgd_start <= 1:
        raise ConfigurationError("PowerSGD error feedback or warm start requires --powersgd-start > 1")
    if args.distributed_timeout_s < 1:
        raise ConfigurationError("--distributed-timeout-s must be positive")
    if args.calibration_max_rank_bytes < 1024:
        raise ConfigurationError("--calibration-max-rank-bytes must be at least 1024")
    if args.accelerator == "cuda" and args.backend not in ("auto", "nccl"):
        raise ConfigurationError("CUDA continuity runs require the NCCL backend")
    if args.accelerator == "xpu" and args.backend not in ("auto", "ccl"):
        raise ConfigurationError("XPU continuity runs require the oneCCL backend")
    if args.profile == "paper":
        expected = {
            "batch_size": PAPER_BATCH_SIZE,
            "iters": PAPER_MEASURED_ITERS,
            "warmup_iters": PAPER_WARMUP_ITERS,
        }
        mismatches = [f"{key}={getattr(args, key)} (expected {value})" for key, value in expected.items()
                      if getattr(args, key) != value]
        if not math.isclose(args.topk_frac, PAPER_TOPK_FRAC, rel_tol=0.0, abs_tol=1e-12):
            mismatches.append(f"topk_frac={args.topk_frac} (expected {PAPER_TOPK_FRAC})")
        if args.comm_mode == "gpu-topk" and not args.topk_error_feedback:
            mismatches.append("Top-k error feedback disabled")
        if mismatches:
            raise ConfigurationError("paper profile differs from the frozen condition: " + "; ".join(mismatches))
    elif args.skip_calibration is False:
        # Qualification runs may retain calibration; the profile is still labeled non-paper.
        pass
    if args.input_pool < 0:
        raise ConfigurationError("--input-pool cannot be negative")
    if not (1 <= args.seq_len <= 2048):
        raise ConfigurationError("--seq-len must be in [1, 2048]")
    if args.seq_len != 2048 and args.model != "llama1b":
        raise ConfigurationError("--seq-len applies to the llama1b workload only")
    args.calibration_size_list = parse_calibration_sizes(args.calibration_sizes)
    args.trace_rank_list = parse_rank_list(args.trace_ranks)
    if args.accelerator == "cpu" and args.backend not in ("auto", "gloo"):
        raise ConfigurationError("CPU runs require the gloo backend")
    if args.backend == "gloo" and args.accelerator != "cpu":
        raise ConfigurationError("the gloo backend is for CPU qualification runs only")
    if args.accelerator == "cpu" and args.profile != "qualification":
        raise ConfigurationError("CPU runs are local qualification tests only")
    if args.profile == "validation":
        expected = {
            "iters": VALIDATION_MEASURED_ITERS,
            "warmup_iters": VALIDATION_WARMUP_ITERS,
            "input_pool": VALIDATION_INPUT_POOL,
        }
        mismatches = [f"{key}={getattr(args, key)} (expected {value})" for key, value in expected.items()
                      if getattr(args, key) != value]
        if args.trace_dir is not None or args.verify_equivalence or args.sync_debug != "off":
            mismatches.append("validation runs carry no trace, equivalence check, or sync debugging")
        if not math.isclose(args.topk_frac, PAPER_TOPK_FRAC, rel_tol=0.0, abs_tol=1e-12):
            mismatches.append(f"topk_frac={args.topk_frac} (expected {PAPER_TOPK_FRAC})")
        if mismatches:
            raise ConfigurationError("validation profile differs from the frozen condition: "
                                     + "; ".join(mismatches))
    validate_v52(args)
    return args


def parse_args(argv: Optional[Sequence[str]] = None) -> argparse.Namespace:
    parser = build_parser()
    args = parser.parse_args(argv)
    try:
        return validate_config(args)
    except ConfigurationError as exc:
        parser.error(str(exc))
        raise AssertionError("argparse.error must terminate") from exc


def condition_deviations(args: argparse.Namespace) -> List[str]:
    deviations: List[str] = []
    if args.profile != "paper":
        deviations.append(f"{args.profile}_profile_not_paper_evidence")
    if args.batch_size != PAPER_BATCH_SIZE:
        deviations.append(f"batch_size={args.batch_size};paper={PAPER_BATCH_SIZE}")
    if args.iters != PAPER_MEASURED_ITERS:
        deviations.append(f"measured_iterations={args.iters};paper={PAPER_MEASURED_ITERS}")
    if args.warmup_iters != PAPER_WARMUP_ITERS:
        deviations.append(f"warmup_iterations={args.warmup_iters};paper={PAPER_WARMUP_ITERS}")
    if not math.isclose(args.topk_frac, PAPER_TOPK_FRAC, rel_tol=0.0, abs_tol=1e-12):
        deviations.append(f"topk_fraction={args.topk_frac};paper={PAPER_TOPK_FRAC}")
    if args.comm_mode == "gpu-topk" and not args.topk_error_feedback:
        deviations.append("legacy_topk_error_feedback_disabled")
    if args.skip_calibration and not (
        args.profile == "paper" and args.calibration_reference is not None
    ):
        deviations.append("alpha_beta_calibration_skipped")
    if args.comm_mode in OVERLAP_MODES:
        deviations.append("supplemental_overlap_baseline_not_in_legacy_matrix")
    if args.comm_mode in HOOK_MODES:
        deviations.append(f"production_comm_hook_{args.comm_mode}")
    if args.comm_mode in CONTROL_MODES:
        deviations.append("control_mode_not_in_legacy_matrix")
    if args.timing_mode != "phase":
        deviations.append("uninstrumented_wall_clock_timing")
    if args.tau_no_barrier:
        deviations.append("tau_sweep_without_per_iteration_barrier")
    if args.verify_equivalence:
        deviations.append("equivalence_verification_mode_not_timing_evidence")
