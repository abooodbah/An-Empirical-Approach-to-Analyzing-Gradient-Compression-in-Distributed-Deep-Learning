@dataclass(frozen=True)
class AcceleratorRuntime:
    kind: str
    backend: str
    rank: int
    world_size: int
    local_rank: int
    device: torch.device
    ccl_binding: Optional[Mapping[str, str]] = None

    def synchronize(self) -> None:
        SYNC_COUNTER[0] += 1
        if self.kind == "cpu":
            return
        if self.kind == "cuda":
            torch.cuda.synchronize(self.device)
        elif self.kind == "xpu":
            try:
                torch.xpu.synchronize(self.device)
            except TypeError:
                torch.xpu.synchronize()
        else:  # pragma: no cover - construction prevents this
            raise RuntimeError(f"unsupported accelerator {self.kind}")

    def reset_peak_memory(self) -> None:
        if self.kind == "cuda":
            torch.cuda.reset_peak_memory_stats(self.device)
        elif self.kind == "xpu" and hasattr(torch.xpu, "reset_peak_memory_stats"):
            torch.xpu.reset_peak_memory_stats(self.device)

    def peak_memory_mb(self) -> Optional[float]:
        if self.kind == "cuda":
            return float(torch.cuda.max_memory_allocated(self.device)) / 1e6
        if self.kind == "cpu":
            return None
        getter = getattr(torch.xpu, "max_memory_allocated", None)
        return float(getter(self.device)) / 1e6 if getter is not None else None

    def device_name(self) -> str:
        if self.kind == "cuda":
            return str(torch.cuda.get_device_name(self.device))
        if self.kind == "cpu":
            return platform.processor() or "cpu"
        getter = getattr(torch.xpu, "get_device_name", None)
        if getter is None:
            return str(self.device)
        try:
            return str(getter(self.device))
        except TypeError:
            return str(getter(self.local_rank))


def _require_distributed_environment() -> Tuple[int, int, int]:
    required = ("RANK", "WORLD_SIZE", "LOCAL_RANK", "MASTER_ADDR", "MASTER_PORT")
    missing = [key for key in required if key not in os.environ]
    if missing:
        raise RuntimeError(
            "distributed launch is required; missing torchrun variables: " + ", ".join(missing)
        )
    rank = int(os.environ["RANK"])
    world_size = int(os.environ["WORLD_SIZE"])
    local_rank = int(os.environ["LOCAL_RANK"])
    if world_size < 1 or not (0 <= rank < world_size) or local_rank < 0:
        raise RuntimeError("invalid RANK/WORLD_SIZE/LOCAL_RANK values")
    return rank, world_size, local_rank


def _package_version(*names: str) -> Optional[str]:
    for name in names:
        try:
            return importlib.metadata.version(name)
        except importlib.metadata.PackageNotFoundError:
            continue
    return None


def _load_ccl_binding() -> Mapping[str, str]:
    try:
        module = importlib.import_module("oneccl_bindings_for_pytorch")
    except Exception as exc:
        raise RuntimeError(
            "XPU was requested but oneccl_bindings_for_pytorch could not be imported; "
            "a host-staging or Gloo substitute is intentionally forbidden"
        ) from exc
    version = str(
        getattr(module, "__version__", None)
        or _package_version("oneccl_bind_pt", "oneccl-bind-pt", "oneccl_bindings_for_pytorch")
        or "unknown"
    )
    if "+cpu" in version.lower() or version.lower().endswith("-cpu"):
        raise RuntimeError(
            f"oneCCL binding reports CPU-only build {version!r}; an XPU-capable binding is required"
        )
    return {"version": version, "module_file": str(getattr(module, "__file__", "unknown"))}


def _distributed_barrier(runtime: AcceleratorRuntime) -> None:
    if runtime.backend == "nccl":
        try:
            dist.barrier(device_ids=[runtime.local_rank])
            return
        except TypeError:
            pass
    dist.barrier()


def _probe_collectives(runtime: AcceleratorRuntime) -> Mapping[str, Any]:
    """Fail before the workload if required accelerator collectives are not real/usable."""
    expected_sum = runtime.world_size * (runtime.world_size + 1) / 2.0
    fp = torch.tensor([float(runtime.rank + 1)], dtype=torch.float32, device=runtime.device)
    dist.all_reduce(fp)
    runtime.synchronize()
    observed = float(fp.cpu().item())
    if not math.isclose(observed, expected_sum, rel_tol=1e-6, abs_tol=1e-6):
        raise RuntimeError(f"float32 all-reduce probe returned {observed}, expected {expected_sum}")

    byte = torch.tensor([runtime.rank % 251, 17], dtype=torch.uint8, device=runtime.device)
    byte_out = [torch.empty_like(byte) for _ in range(runtime.world_size)]
    dist.all_gather(byte_out, byte)
    long_value = torch.tensor([runtime.rank], dtype=torch.int64, device=runtime.device)
    long_out = [torch.empty_like(long_value) for _ in range(runtime.world_size)]
    dist.all_gather(long_out, long_value)
    runtime.synchronize()
    byte_values = [int(value[0].cpu().item()) for value in byte_out]
    long_values = [int(value.cpu().item()) for value in long_out]
    if byte_values != [rank % 251 for rank in range(runtime.world_size)]:
        raise RuntimeError(f"uint8 all-gather probe mismatch: {byte_values}")
    if long_values != list(range(runtime.world_size)):
        raise RuntimeError(f"int64 all-gather probe mismatch: {long_values}")
    _distributed_barrier(runtime)
    runtime.synchronize()
    return {
        "float32_allreduce": "pass",
        "uint8_allgather": "pass",
        "int64_allgather": "pass",
        "expected_float32_sum": expected_sum,
    }


def initialize_distributed(args: argparse.Namespace) -> Tuple[AcceleratorRuntime, Mapping[str, Any]]:
    if _TORCH_IMPORT_ERROR is not None:
        raise RuntimeError(
            "PyTorch is required for benchmark execution (the schema/CLI may be inspected without it)"
        ) from _TORCH_IMPORT_ERROR
    if not dist.is_available():
        raise RuntimeError("torch.distributed is unavailable in this PyTorch build")
    rank, world_size, local_rank = _require_distributed_environment()

    accelerator = args.accelerator
    if accelerator == "auto":
        if torch.cuda.is_available():
            accelerator = "cuda"
        elif hasattr(torch, "xpu") and torch.xpu.is_available():
            accelerator = "xpu"
        else:
            raise RuntimeError("neither a CUDA nor an XPU accelerator is available")

    ccl_binding: Optional[Mapping[str, str]] = None
    if accelerator == "cuda":
        if not torch.cuda.is_available():
            raise RuntimeError("CUDA was requested but torch.cuda.is_available() is false")
        if local_rank >= torch.cuda.device_count():
            raise RuntimeError(f"LOCAL_RANK={local_rank} exceeds {torch.cuda.device_count()} visible CUDA devices")
        torch.cuda.set_device(local_rank)
        backend = "nccl" if args.backend == "auto" else args.backend
        if backend != "nccl" or not dist.is_nccl_available():
            raise RuntimeError("CUDA continuity execution requires an available NCCL backend")
        device = torch.device("cuda", local_rank)
    elif accelerator == "xpu":
        try:
            ipex_module = importlib.import_module("intel_extension_for_pytorch")
        except Exception as exc:
            raise RuntimeError(
                "XPU was requested but intel_extension_for_pytorch could not be imported"
            ) from exc
        ipex_version = str(
            getattr(ipex_module, "__version__", None)
            or _package_version("intel-extension-for-pytorch")
            or "unknown"
        )
        if "xpu" not in ipex_version.lower():
            raise RuntimeError(
                f"Intel Extension for PyTorch is not an XPU build: {ipex_version!r}"
            )
        if not hasattr(torch, "xpu") or not torch.xpu.is_available():
            raise RuntimeError("XPU was requested but torch.xpu.is_available() is false")
        if local_rank >= torch.xpu.device_count():
            raise RuntimeError(f"LOCAL_RANK={local_rank} exceeds {torch.xpu.device_count()} visible XPU devices")
        torch.xpu.set_device(local_rank)
        ccl_binding = _load_ccl_binding()
        backend = "ccl" if args.backend == "auto" else args.backend
        if backend != "ccl":
            raise RuntimeError("XPU continuity execution requires CCL; substitutes are not allowed")
        ccl_checker = getattr(dist, "is_ccl_available", None)
        if ccl_checker is not None and not ccl_checker():
            raise RuntimeError("oneCCL binding imported, but torch.distributed reports CCL unavailable")
        device = torch.device("xpu", local_rank)
    elif accelerator == "cpu":
        backend = "gloo" if args.backend == "auto" else args.backend
        if backend != "gloo":
            raise RuntimeError("CPU qualification runs use the gloo backend")
        device = torch.device("cpu")
    else:  # pragma: no cover - argparse constrains this
        raise RuntimeError(f"unsupported accelerator {accelerator}")

    timeout = dt.timedelta(seconds=args.distributed_timeout_s)
    try:
        dist.init_process_group(backend=backend, init_method="env://", timeout=timeout)
    except Exception as exc:
        detail = " (XPU-capable oneCCL initialization failed)" if accelerator == "xpu" else ""
        raise RuntimeError(f"could not initialize {backend} process group{detail}: {exc}") from exc
    runtime = AcceleratorRuntime(
        kind=accelerator,
        backend=backend,
        rank=rank,
        world_size=world_size,
        local_rank=local_rank,
        device=device,
        ccl_binding=ccl_binding,
    )
    if dist.get_rank() != rank or dist.get_world_size() != world_size:
        raise RuntimeError("process-group rank/world size differs from torchrun environment")
    probe = _probe_collectives(runtime)
    return runtime, probe


def seed_everything(seed: int, runtime: AcceleratorRuntime) -> None:
    random.seed(seed)
    np.random.seed(seed % (2**32))
    torch.manual_seed(seed)
    if runtime.kind == "cuda":
        torch.cuda.manual_seed_all(seed)
        torch.backends.cudnn.benchmark = False
        torch.backends.cudnn.deterministic = True
    elif runtime.kind == "xpu":
        manual_seed_all = getattr(torch.xpu, "manual_seed_all", None)
        if manual_seed_all is not None:
            manual_seed_all(seed)


class SmallTransformer(nn.Module):
    """Exact synthetic Transformer architecture used in the submitted paper harness."""

    def __init__(self, d_model: int = 512, nhead: int = 8, nlayers: int = 2, vocab: int = 10000):
        super().__init__()
        self.emb = nn.Embedding(vocab, d_model)
        self.enc = nn.TransformerEncoder(nn.TransformerEncoderLayer(d_model, nhead), nlayers)
        self.cls = nn.Linear(d_model, 2)

    def forward(self, tokens: torch.Tensor) -> torch.Tensor:
        hidden = self.emb(tokens).permute(1, 0, 2)
        hidden = self.enc(hidden)
        return self.cls(hidden[0])


class RMSNorm(nn.Module):
    def __init__(self, dim: int, eps: float = 1e-5):
        super().__init__()
        self.weight = nn.Parameter(torch.ones(dim))
        self.eps = eps

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        return x * torch.rsqrt(x.pow(2).mean(-1, keepdim=True) + self.eps) * self.weight


class LlamaBlock(nn.Module):
    def __init__(self, d_model: int, n_heads: int, ffn: int):
        super().__init__()
        self.norm1 = RMSNorm(d_model)
        self.norm2 = RMSNorm(d_model)
        self.qkv = nn.Linear(d_model, 3 * d_model, bias=False)
        self.out = nn.Linear(d_model, d_model, bias=False)
        self.w1 = nn.Linear(d_model, ffn, bias=False)
        self.w3 = nn.Linear(d_model, ffn, bias=False)
        self.w2 = nn.Linear(ffn, d_model, bias=False)
        self.n_heads = n_heads

    def forward(self, x: torch.Tensor, mask: torch.Tensor) -> torch.Tensor:
        batch, length, width = x.shape
        head_dim = width // self.n_heads
        hidden = self.norm1(x)
        q, k, v = self.qkv(hidden).view(batch, length, 3, self.n_heads, head_dim).unbind(2)
        q = q.transpose(1, 2)
        k = k.transpose(1, 2)
        v = v.transpose(1, 2)
        scores = torch.matmul(q, k.transpose(-2, -1)) / math.sqrt(head_dim)
        scores = scores.masked_fill(mask, float("-inf"))
        attention = torch.softmax(scores, dim=-1)
        mixed = torch.matmul(attention, v).transpose(1, 2).reshape(batch, length, width)
        x = x + self.out(mixed)
        hidden = self.norm2(x)
        return x + self.w2(torch.nn.functional.silu(self.w1(hidden)) * self.w3(hidden))


class LlamaStyleLM(nn.Module):
    """Decoder-only Transformer in the LLaMA family: RMSNorm, SwiGLU, causal
    attention, learned positions. Attention is written out explicitly so the
    same code runs on the torch 1.13 XPU stack and the torch 2.4 CUDA stack."""

    def __init__(self, d_model: int = 2048, n_layers: int = 18, n_heads: int = 16,
                 ffn: int = 5504, vocab: int = 32000, seq: int = 2048):
        super().__init__()
        self.tok = nn.Embedding(vocab, d_model)
        self.pos = nn.Embedding(seq, d_model)
        self.blocks = nn.ModuleList([LlamaBlock(d_model, n_heads, ffn) for _ in range(n_layers)])
        self.norm = RMSNorm(d_model)
        self.head = nn.Linear(d_model, vocab, bias=False)

    def forward(self, tokens: torch.Tensor) -> torch.Tensor:
        batch, length = tokens.shape
        positions = torch.arange(length, device=tokens.device)
        x = self.tok(tokens) + self.pos(positions)
        mask = torch.triu(torch.ones(length, length, dtype=torch.bool, device=tokens.device), diagonal=1)
        for block in self.blocks:
            x = block(x, mask)
        logits = self.head(self.norm(x))
        return logits.transpose(1, 2)


