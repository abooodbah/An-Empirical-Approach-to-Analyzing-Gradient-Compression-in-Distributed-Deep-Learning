def validate_result_record(record: Mapping[str, Any]) -> None:
    missing = [field for field in RESULT_FIELDS if field not in record]
    extra = [field for field in record if field not in RESULT_FIELDS]
    if missing or extra:
        raise ValueError(f"result schema mismatch; missing={missing}, extra={extra}")
    if record["schema_version"] != SCHEMA_VERSION:
        raise ValueError("incorrect schema version")
    for field in (
        "campaign_id", "track", "run_id", "timing_semantics", "software_versions", "status",
        "provenance_file",
    ):
        if not isinstance(record[field], str) or not record[field]:
            raise ValueError(f"{field} must be a nonempty string")
    calibration_reference = record["calibration_reference"]
    if calibration_reference is not None and (
        not isinstance(calibration_reference, str)
        or re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9._-]{0,127}", calibration_reference) is None
    ):
        raise ValueError("calibration_reference must be null or a valid run identifier")
    try:
        software_versions = json.loads(record["software_versions"])
    except (TypeError, json.JSONDecodeError) as exc:
        raise ValueError("software_versions must contain canonical JSON") from exc
    if not isinstance(software_versions, dict):
        raise ValueError("software_versions JSON must be an object")
    if record["model"] not in MODELS or record["comm_mode"] not in COMM_MODES:
        raise ValueError("invalid model or communication mode in result")
    if record["mode"] != record["comm_mode"]:
        raise ValueError("mode and comm_mode must agree")
    if record["timing_mode"] not in TIMING_MODES:
        raise ValueError("invalid timing mode in result")
    if record["track"] not in ("legacy-continuity", "overlap-baseline", "control-extension"):
        raise ValueError("invalid evidence track")
    if record["status"] not in ("PASS", "QUALIFICATION_ONLY"):
        raise ValueError("invalid completion status")
    if record["status"] == "PASS" and record["validated_sample_count"] != record["measured_iterations"]:
        raise ValueError("PASS requires every declared iteration to validate")
    if (record["status"] == "PASS" and record["profile"] != "validation"
            and record["validated_sample_count"] != PAPER_MEASURED_ITERS):
        raise ValueError("PASS requires exactly 40 validated samples outside the validation profile")
    if record["accelerator"] == "cpu" and record["status"] == "PASS":
        raise ValueError("CPU runs are never PASS")
    for field in ("nodes", "ranks_per_node", "world_size", "local_batch_size", "global_batch_size"):
        if not isinstance(record[field], int) or record[field] < 1:
            raise ValueError(f"{field} must be a positive integer")
    if record["nodes"] * record["ranks_per_node"] != record["world_size"]:
        raise ValueError("node layout does not multiply to world size")
    if not isinstance(record["paper_condition"], bool) or not isinstance(record["do_communication"], bool):
        raise ValueError("paper_condition and do_communication must be booleans")
    for field in TIMING_FIELDS:
        value = record[field]
        if value is not None and (not isinstance(value, (int, float)) or not math.isfinite(value) or value < 0):
            raise ValueError(f"{field} must be null or a finite nonnegative number")
    for field in ("block_elapsed_s", "block_elapsed_max_s", "block_step_equiv_s"):
        value = record[field]
        if not isinstance(value, (int, float)) or not math.isfinite(value) or value < 0:
            raise ValueError(f"{field} must be a finite nonnegative number")
    if record["block_iterations"] != record["measured_iterations"]:
        raise ValueError("block_iterations must equal the measured iterations")
    if record["timing_mode"] == "block" and record["observed_step_s"] is not None:
        raise ValueError("block-timed rows carry no per-step time")
    for field in ("loss", "compression_ratio", "peak_memory_mb"):
        value = record[field]
        if value is not None and (not isinstance(value, (int, float)) or not math.isfinite(value)):
            raise ValueError(f"{field} must be null or finite")
    for field in ("gradient_elements", "bytes_uncompressed", "legacy_bytes_onwire_estimate",
                  "collective_input_bytes_per_rank"):
        value = record[field]
        if value is not None and (not isinstance(value, int) or value < 0):
            raise ValueError(f"{field} must be null or a nonnegative integer")
    if record["comm_mode"] in OVERLAP_MODES and record["network_s"] is not None:
        raise ValueError("overlap baseline must not claim a separable network time")
    if record["comm_mode"] == "gpu-topk" and record["topk_residual_semantics"] != LEGACY_TOPK_RESIDUAL:
        raise ValueError("Top-k rows must declare the retained legacy residual semantics")
    if record["comm_mode"] == "gpu-topk-localef" and record["topk_residual_semantics"] != LOCALEF_TOPK_RESIDUAL:
        raise ValueError("local-EF Top-k rows must declare the standard residual semantics")
    json.dumps(dict(record), allow_nan=False)


def _safe_filename(value: str) -> str:
    return re.sub(r"[^A-Za-z0-9._-]+", "-", value).strip("-._") or "run"


def _atomic_write(path: Path, content: str) -> None:
    temporary = path.with_name(f".{path.name}.tmp.{os.getpid()}")
    with temporary.open("w", encoding="utf-8", newline="") as handle:
        handle.write(content)
        handle.flush()
        os.fsync(handle.fileno())
    os.replace(temporary, path)


def write_evidence(
    records: Sequence[Mapping[str, Any]],
    provenance: Mapping[str, Any],
    output_dir: Path,
    prefix: str,
) -> Mapping[str, str]:
    output_dir.mkdir(parents=True, exist_ok=True)
    for record in records:
        validate_result_record(record)
    declared_counts = {record["validated_sample_count"] for record in records}
    if declared_counts != {len(records)}:
        raise ValueError(
            f"result file contains {len(records)} rows but declares validated counts {declared_counts}"
        )
    if any(record["status"] == "PASS" for record in records):
        declared = records[0]["measured_iterations"]
        if len(records) != declared:
            raise ValueError("PASS evidence file must contain every declared measured row")
        if [record["iteration"] for record in records] != list(range(declared)):
            raise ValueError("PASS evidence file must contain the complete ordered iteration sequence")

    csv_buffer = io.StringIO(newline="")
    writer = csv.DictWriter(csv_buffer, fieldnames=RESULT_FIELDS, extrasaction="raise")
    writer.writeheader()
    writer.writerows(records)
    csv_path = output_dir / f"{prefix}.csv"
    jsonl_path = output_dir / f"{prefix}.jsonl"
    provenance_path = output_dir / f"{prefix}.provenance.json"
    _atomic_write(csv_path, csv_buffer.getvalue())
    _atomic_write(
        jsonl_path,
        "".join(json.dumps(dict(record), sort_keys=True, allow_nan=False) + "\n" for record in records),
    )
    _atomic_write(
        provenance_path,
        json.dumps(dict(provenance), indent=2, sort_keys=True, allow_nan=False) + "\n",
    )
    return {"csv": str(csv_path), "jsonl": str(jsonl_path), "provenance": str(provenance_path)}


