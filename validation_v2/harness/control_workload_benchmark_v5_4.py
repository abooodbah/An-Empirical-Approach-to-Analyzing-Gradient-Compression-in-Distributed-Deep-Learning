class ConfigurationError(ValueError):
    """Raised when a requested condition is not part of the declared contract."""


def utc_now() -> str:
    return dt.datetime.now(dt.timezone.utc).isoformat(timespec="milliseconds")


def canonical_comm_mode(value: str) -> str:
    normalized = value.strip().lower().replace("_", "-")
    aliases = {
        "powersgd": "powersgd",
        "power-sgd": "powersgd",
        "ddp": "ddp-overlap",
        "ddp-overlap": "ddp-overlap",
    }
    normalized = aliases.get(normalized, normalized)
    if normalized not in COMM_MODES:
        raise argparse.ArgumentTypeError(
            f"unsupported communication mode {value!r}; choose one of {', '.join(COMM_MODES)}"
        )
    return normalized


def parse_calibration_sizes(value: Optional[str]) -> Optional[Tuple[int, ...]]:
    """Comma-separated payload sizes in bytes; None when unset."""
    if value is None or not str(value).strip():
        return None
    try:
        sizes = tuple(int(item) for item in str(value).split(",") if item.strip())
    except ValueError as exc:
        raise ConfigurationError("--calibration-sizes must list integers") from exc
    if not sizes or any(size < 4 for size in sizes):
        raise ConfigurationError("--calibration-sizes must list payload sizes of at least 4 bytes")
    return tuple(sorted(set(sizes)))


def parse_rank_list(value: str) -> Tuple[int, ...]:
    try:
        ranks = tuple(sorted({int(item) for item in str(value).split(",") if item.strip()}))
    except ValueError as exc:
        raise ConfigurationError("--trace-ranks must list integers") from exc
    if any(rank < 0 for rank in ranks):
        raise ConfigurationError("--trace-ranks must be nonnegative")
    return ranks


def block_step_equivalent(elapsed_by_rank: Sequence[float], iterations: int) -> Tuple[float, float]:
    """Maximum rank-local block time and that maximum divided by the number
    of iterations: the step-equivalent wall time reported for every timing
    convention."""
    if iterations < 1 or len(elapsed_by_rank) == 0:
        raise ValueError("block timing needs at least one iteration and one rank")
    values = [float(value) for value in elapsed_by_rank]
    if any((not math.isfinite(value)) or value < 0 for value in values):
        raise ValueError("block times must be finite and nonnegative")
    maximum = max(values)
    return maximum, maximum / iterations


