def broadcast_model(model: nn.Module, runtime: AcceleratorRuntime) -> None:
    for tensor in model.state_dict().values():
        if tensor.numel() > 0:
            dist.broadcast(tensor, src=0)
    runtime.synchronize()


def model_sha256(model: nn.Module) -> str:
    digest = hashlib.sha256()
    for name, tensor in model.state_dict().items():
        digest.update(name.encode("utf-8"))
        cpu = tensor.detach().cpu().contiguous()
        digest.update(str(cpu.dtype).encode("ascii"))
        digest.update(np.asarray(cpu).tobytes(order="C"))
    return digest.hexdigest()


def params_sha256(model: nn.Module) -> str:
    """Hash the learned parameters only. The full state_dict hash above
    also covers buffers (BatchNorm running statistics), which legitimately
    differ across ranks under per-rank inputs; this hash isolates the
    quantity the validity rules name: the parameters."""
    digest = hashlib.sha256()
    for name, tensor in sorted(model.named_parameters(), key=lambda kv: kv[0]):
        digest.update(name.encode("utf-8"))
        cpu = tensor.detach().cpu().contiguous()
        digest.update(str(cpu.dtype).encode("ascii"))
        digest.update(np.asarray(cpu).tobytes(order="C"))
    return digest.hexdigest()


def gather_hashes(local_hash: str, runtime: AcceleratorRuntime) -> List[str]:
    encoded = torch.tensor(list(bytes.fromhex(local_hash)), dtype=torch.uint8, device=runtime.device)
    gathered = [torch.empty_like(encoded) for _ in range(runtime.world_size)]
    dist.all_gather(gathered, encoded)
    runtime.synchronize()
    return [bytes(int(value) for value in item.cpu().tolist()).hex() for item in gathered]


def gather_host_layout(runtime: AcceleratorRuntime) -> Mapping[str, Any]:
    """Derive node/rank layout from observed hostnames, not scheduler assumptions."""
    hostname = socket.gethostname()
    encoded_hostname = hostname.encode("utf-8")
    if not encoded_hostname or len(encoded_hostname) > 255 or b"\x00" in encoded_hostname:
        raise RuntimeError(f"hostname cannot be encoded in the collective layout probe: {hostname!r}")
    encoded = torch.zeros(256, dtype=torch.uint8, device=runtime.device)
    encoded[0] = len(encoded_hostname)
    encoded[1:1 + len(encoded_hostname)] = torch.tensor(
        list(encoded_hostname), dtype=torch.uint8, device=runtime.device
    )
    gathered = [torch.empty_like(encoded) for _ in range(runtime.world_size)]
    dist.all_gather(gathered, encoded)
    runtime.synchronize()
    hostnames: List[str] = []
    for item in gathered:
        host_bytes = item.cpu().tolist()
        length = int(host_bytes[0])
        hostnames.append(bytes(host_bytes[1:1 + length]).decode("utf-8"))
    counts: Dict[str, int] = {}
    for observed in hostnames:
        counts[observed] = counts.get(observed, 0) + 1
    if len(set(counts.values())) != 1:
        raise RuntimeError(f"unbalanced ranks-per-node layout is outside this contract: {counts}")
    return {
        "hostnames_by_rank": hostnames,
        "rank_counts_by_hostname": counts,
        "nodes": len(counts),
        "ranks_per_node": next(iter(counts.values())),
    }


def flatten_grads(model: nn.Module, device: torch.device) -> torch.Tensor:
    parts = [parameter.grad.detach().to(torch.float32).reshape(-1)
             for parameter in model.parameters() if parameter.grad is not None]
    return torch.cat(parts) if parts else torch.empty(0, dtype=torch.float32, device=device)


def unflatten_and_copy(model: nn.Module, flat: torch.Tensor) -> None:
    offset = 0
    for parameter in model.parameters():
        if parameter.grad is None:
            continue
        size = parameter.numel()
        parameter.grad.copy_(flat[offset:offset + size].view_as(parameter.grad))
        offset += size
    if offset != flat.numel():
        raise RuntimeError(f"gradient reconstruction consumed {offset} values, expected {flat.numel()}")


def gpu_quantize(tensor: torch.Tensor) -> Tuple[torch.Tensor, torch.Tensor]:
    if tensor.numel() == 0:
        return torch.ones(1, dtype=torch.float32, device=tensor.device), torch.empty(
            0, dtype=torch.uint8, device=tensor.device
        )
    maximum = tensor.abs().max().to(torch.float32)
    scale = torch.where(maximum > 0, maximum / 127.0, torch.ones_like(maximum)).reshape(1)
    signed = torch.round(tensor / scale).clamp(-128, 127).to(torch.int16)
    encoded = (signed + 128).to(torch.uint8)
    return scale, encoded


def gpu_dequantize(scale: torch.Tensor, encoded: torch.Tensor, n: int) -> torch.Tensor:
    if encoded.numel() != n:
        raise RuntimeError(f"quantized payload contains {encoded.numel()} bytes, expected {n}")
    signed = encoded.to(torch.int16) - 128
    return signed.to(torch.float32) * scale.reshape(1)[0]


def bucket_bounds(n: int, bucket_elems: int) -> List[Tuple[int, int]]:
    """Half-open slices that cover n elements in order; the last may be short."""
    if bucket_elems < 1:
        raise ConfigurationError("--exchange-bucket-elems must be positive for a bucketed mode")
    return [(start, min(n, start + bucket_elems)) for start in range(0, n, bucket_elems)]


def exchange_buffer_bytes(mode: str, world_size: int, bucket_elems: int) -> int:
    """Bytes of exchange buffers this harness holds at once in a bucketed
    mode, beyond the flat gradient, its encoded copy, and the FP32 result,
    which the whole-gradient modes hold too. The backend may hold more
    inside a collective; the measured peak is recorded beside this."""
    if mode == "gpu-quant-bucketed":
        return world_size * bucket_elems + 4 * bucket_elems
    if mode in ("gpu-quant-reducible-bucketed", "native-bucketed"):
        return 0
    raise ConfigurationError(f"{mode} is not a bucketed mode")


def bucket_buffers(runtime: Any, bucket_elems: int, n: int, received_count: int) -> Dict[str, Any]:
    """Buffers of the bucketed gather, allocated once per run and reused for
    every bucket and iteration."""
    state = HOOK_STATE.get("_bucket_buffers")
    width = min(bucket_elems, n)
    if state is None or state["result"].numel() != n or state["scratch"].numel() != width:
        state = {
            "received": [torch.empty(width, dtype=torch.uint8, device=runtime.device)
                         for _ in range(received_count)],
            "scratch": torch.empty(width, dtype=torch.float32, device=runtime.device),
            "result": torch.empty(n, dtype=torch.float32, device=runtime.device),
        }
        HOOK_STATE["_bucket_buffers"] = state
    return state


def levels_int8(world_size: int) -> int:
    """Levels per side whose exact sum over the ranks fits a signed byte."""
    return max(1, 127 // world_size)


def levels_fp16(world_size: int) -> int:
    """Levels per side whose exact sum fits float16, exact to 2048."""
    return 2048 // world_size


def stochastic_generator(runtime: Any, rank_seed: int) -> Optional[Any]:
    """One generator per run and rank, seeded apart from the model and data
    streams. A backend without device generators uses the global stream,
    which seed_everything already seeds per rank."""
    if "_stochastic_generator" not in HOOK_STATE:
        try:
            generator = torch.Generator(device=runtime.device)
            generator.manual_seed(rank_seed + 7919)
        except (RuntimeError, TypeError):
            generator = None
        HOOK_STATE["_stochastic_generator"] = generator
    return HOOK_STATE["_stochastic_generator"]


def stochastic_levels(values: Any, scale: Any, levels: float, generator: Optional[Any]) -> Any:
    """floor(values / scale + u), u uniform on [0, 1), clamped to the level
    range: an unbiased shared-scale quantizer."""
    noise = torch.rand(values.shape, generator=generator, device=values.device, dtype=torch.float32)
    return torch.clamp(torch.floor(values / scale + noise), min=-levels, max=levels)


