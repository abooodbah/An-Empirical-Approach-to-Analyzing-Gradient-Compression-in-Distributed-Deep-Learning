"""Generate control_workload_benchmark_v5.py from v4 (TPDS v2, 2026-09-23).

Adds, leaving every v4 code path unchanged when the new options are unset
(except that per-iteration records are now assembled after the measured
loop in every mode, which moves host-side bookkeeping out of the timed
block; per-step phase timers are unaffected):
  * --timing-mode block (convention B): no measurement synchronization and
    no explicit barrier inside the measured block. The ranks pass a barrier
    and complete pending device work before the block, and the device is
    synchronized once after it. Per-step and phase fields are null.
  * an outer block timer in every timing mode: block_elapsed_s (this rank),
    block_elapsed_max_s (maximum over ranks, gathered after the block), and
    block_step_equiv_s = block_elapsed_max_s / N.
  * --input-pool K: K input batches generated before the block and reused in
    turn, in every mode (0 keeps v4's fresh batch per iteration).
  * --seq-len for the LLaMA-style workload (the positions table stays 2048,
    so the parameter count is unchanged).
  * --calibration-sizes: collective calibration at named payload sizes.
  * --trace-dir/--trace-ranks: torch.profiler Chrome trace of the measured
    loop on the named ranks. Such runs are labeled and are not timing
    evidence.
  * --sync-debug warn: torch.cuda.set_sync_debug_mode("warn") inside the
    block, to list implicit synchronizations (smoke tests only).
  * --profile validation: warm-up 20, measured 100, input pool 4; PASS when
    all 100 iterations validate.
  * DDP bucket fields of _get_ddp_logging_data() in the provenance.
  * --accelerator cpu --backend gloo for local qualification tests only;
    such runs are never PASS.
"""
