"""Control-campaign variant v3 of the frozen July harness (2026-09-19).

Generated by make_control_harness_v3.py from the v2 control harness (which
the September 18 records cite by hash). Adds the llama1b workload, the
ddp-fp16-hook and ddp-int8-hook production overlap modes, and the
"extension" profile.

v2 header follows.

Generated by make_control_harness.py; the archived
paper_workload_benchmark.py is unchanged. Additions: gpu-quant-reducible
(shared-scale summable int8 over all-reduce), gpu-topk-localef (standard
local error feedback), and --timing-mode wall (uninstrumented step
timing). Phase-mode legacy behavior is byte-identical.

Original header follows.

This program deliberately keeps the model, synthetic input, optimizer, compression,
and periodic-synchronization choices used by ``5.9/workspace/benchmark.py``.  It
also makes four measurement corrections needed for publishable evidence:

* requested models and accelerator backends fail closed instead of falling back;
* model parameters are seeded, broadcast, and hash-checked before measurement;
* every accelerator phase has an explicit synchronization boundary; and
* every rank writes CSV, JSONL, and provenance records (rank zero alone is not a
  sufficient observation of synchronization jitter).

The manual communication modes retain the legacy explicit barrier and isolated
backward/communication phases.  ``gpu-topk`` also deliberately retains the
legacy residual definition ``local_corrected_gradient - global_reconstruction``.
Those choices are prominently labeled in every output row.  ``ddp-overlap`` is a
separate supplemental baseline: it uses ordinary DDP overlap and does not claim a
separable network time.

XPU execution is never emulated.  It requires an importable, non-CPU oneCCL
binding and initializes the ``ccl`` process-group backend on real XPU devices.
"""

