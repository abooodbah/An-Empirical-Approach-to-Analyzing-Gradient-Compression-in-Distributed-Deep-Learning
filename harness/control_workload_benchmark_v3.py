def canonical_comm_mode(value: str) -> str:
    normalized = value.strip().lower().replace("_", "-")
    aliases = {
        "powersgd": "powersgd",
        "power-sgd": "powersgd",
        "ddp": "ddp-overlap",
        "ddp-overlap": "ddp-overlap",
    }
    normalized = aliases.get(normalized, normalized)
    if normalized not in COMM_MODES:
        raise argparse.ArgumentTypeError(
            f"unsupported communication mode {value!r}; choose one of {', '.join(COMM_MODES)}"
        )
    return normalized


