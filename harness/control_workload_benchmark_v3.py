def broadcast_model(model: nn.Module, runtime: AcceleratorRuntime) -> None:
    for tensor in model.state_dict().values():
        if tensor.numel() > 0:
            dist.broadcast(tensor, src=0)
    runtime.synchronize()


def model_sha256(model: nn.Module) -> str:
    digest = hashlib.sha256()
    for name, tensor in model.state_dict().items():
        digest.update(name.encode("utf-8"))
        cpu = tensor.detach().cpu().contiguous()
        digest.update(str(cpu.dtype).encode("ascii"))
        digest.update(np.asarray(cpu).tobytes(order="C"))
    return digest.hexdigest()


def gather_hashes(local_hash: str, runtime: AcceleratorRuntime) -> List[str]:
    encoded = torch.tensor(list(bytes.fromhex(local_hash)), dtype=torch.uint8, device=runtime.device)
    gathered = [torch.empty_like(encoded) for _ in range(runtime.world_size)]
    dist.all_gather(gathered, encoded)
    runtime.synchronize()
    return [bytes(int(value) for value in item.cpu().tolist()).hex() for item in gathered]


def gather_host_layout(runtime: AcceleratorRuntime) -> Mapping[str, Any]:
    """Derive node/rank layout from observed hostnames, not scheduler assumptions."""
    hostname = socket.gethostname()
    encoded_hostname = hostname.encode("utf-8")
    if not encoded_hostname or len(encoded_hostname) > 255 or b"\x00" in encoded_hostname:
        raise RuntimeError(f"hostname cannot be encoded in the collective layout probe: {hostname!r}")
    encoded = torch.zeros(256, dtype=torch.uint8, device=runtime.device)
    encoded[0] = len(encoded_hostname)
    encoded[1:1 + len(encoded_hostname)] = torch.tensor(
        list(encoded_hostname), dtype=torch.uint8, device=runtime.device
    )
    gathered = [torch.empty_like(encoded) for _ in range(runtime.world_size)]
    dist.all_gather(gathered, encoded)
    runtime.synchronize()
    hostnames: List[str] = []
    for item in gathered:
        host_bytes = item.cpu().tolist()
        length = int(host_bytes[0])
        hostnames.append(bytes(host_bytes[1:1 + length]).decode("utf-8"))
    counts: Dict[str, int] = {}
    for observed in hostnames:
        counts[observed] = counts.get(observed, 0) + 1
    if len(set(counts.values())) != 1:
        raise RuntimeError(f"unbalanced ranks-per-node layout is outside this contract: {counts}")
    return {
        "hostnames_by_rank": hostnames,
        "rank_counts_by_hostname": counts,
        "nodes": len(counts),
        "ranks_per_node": next(iter(counts.values())),
    }


def flatten_grads(model: nn.Module, device: torch.device) -> torch.Tensor:
    parts = [parameter.grad.detach().to(torch.float32).reshape(-1)
             for parameter in model.parameters() if parameter.grad is not None]
    return torch.cat(parts) if parts else torch.empty(0, dtype=torch.float32, device=device)


def unflatten_and_copy(model: nn.Module, flat: torch.Tensor) -> None:
    offset = 0
    for parameter in model.parameters():
        if parameter.grad is None:
            continue
        size = parameter.numel()
        parameter.grad.copy_(flat[offset:offset + size].view_as(parameter.grad))
        offset += size
    if offset != flat.numel():
        raise RuntimeError(f"gradient reconstruction consumed {offset} values, expected {flat.numel()}")


def gpu_quantize(tensor: torch.Tensor) -> Tuple[torch.Tensor, torch.Tensor]:
    if tensor.numel() == 0:
        return torch.ones(1, dtype=torch.float32, device=tensor.device), torch.empty(
            0, dtype=torch.uint8, device=tensor.device
        )
    maximum = tensor.abs().max().to(torch.float32)
    scale = torch.where(maximum > 0, maximum / 127.0, torch.ones_like(maximum)).reshape(1)
    signed = torch.round(tensor / scale).clamp(-128, 127).to(torch.int16)
    encoded = (signed + 128).to(torch.uint8)
    return scale, encoded


def gpu_dequantize(scale: torch.Tensor, encoded: torch.Tensor, n: int) -> torch.Tensor:
    if encoded.numel() != n:
        raise RuntimeError(f"quantized payload contains {encoded.numel()} bytes, expected {n}")
    signed = encoded.to(torch.int16) - 128
    return signed.to(torch.float32) * scale.reshape(1)[0]


def cpu_quantize(tensor: torch.Tensor) -> bytes:
    cpu = tensor.detach().cpu().float()
    maximum = float(cpu.abs().max().item()) if cpu.numel() else 0.0
    scale = maximum / 127.0 if maximum > 0 else 1.0
    signed = torch.round(cpu / scale).clamp(-128, 127).to(torch.int16)
    encoded = (signed + 128).to(torch.uint8)
    buffer = io.BytesIO()
    # torch.save is intentionally retained: this condition measures the legacy
    # implementation-specific CPU serialization path, not an optimized codec.
    torch.save((scale, encoded), buffer)
    return buffer.getvalue()


def _load_cpu_quantized_payload(payload: bytes) -> Tuple[float, torch.Tensor]:
    buffer = io.BytesIO(payload)
    try:
        scale, encoded = torch.load(buffer, map_location="cpu", weights_only=True)
    except (TypeError, pickle.UnpicklingError):  # older/incomplete weights-only loaders
        buffer.seek(0)
        # The payload is produced by cpu_quantize inside this authenticated
        # distributed job; this fallback never accepts an external artifact.
        scale, encoded = torch.load(buffer, map_location="cpu")
    return scale, encoded


def cpu_dequantize(payload: bytes, n: int, device: torch.device) -> torch.Tensor:
    if not payload:
        raise RuntimeError("empty CPU-quantized payload")
    scale, encoded = _load_cpu_quantized_payload(payload)
    if encoded.numel() != n:
        raise RuntimeError(f"CPU payload contains {encoded.numel()} values, expected {n}")
    signed = encoded.to(torch.int16) - 128
    return (signed.to(torch.float32) * float(scale)).to(device)


def gpu_topk(tensor: torch.Tensor, k: int) -> Tuple[torch.Tensor, torch.Tensor]:
    if tensor.numel() == 0:
        return (
            torch.empty(0, dtype=torch.int64, device=tensor.device),
            torch.empty(0, dtype=torch.float32, device=tensor.device),
        )
    count = min(max(1, k), tensor.numel())
    _, indices = torch.topk(tensor.abs().reshape(-1), count, sorted=False)
    values = tensor.reshape(-1)[indices].to(torch.float32)
    return indices.to(torch.int64), values


def measure(runtime: AcceleratorRuntime, operation: Callable[[], Any]) -> Tuple[Any, float]:
    runtime.synchronize()
    started = time.perf_counter()
    result = operation()
    runtime.synchronize()
    return result, time.perf_counter() - started


def fit_alpha_beta(
    sizes_bytes: Sequence[int],
    times_s: Sequence[float],
    world_size: int,
    collective: str,
) -> Tuple[float, float, float]:
    if len(sizes_bytes) != len(times_s) or len(sizes_bytes) < 2:
        raise ValueError("alpha-beta fit requires at least two matched observations")
    x = np.asarray(sizes_bytes, dtype=np.float64)
    y = np.asarray(times_s, dtype=np.float64)
    design = np.vstack([x, np.ones(len(x))]).T
    slope, intercept = np.linalg.lstsq(design, y, rcond=None)[0]
    slope = max(1e-12, float(slope))
    intercept = max(1e-9, float(intercept))
    predicted = slope * x + intercept
    residual = float(np.sum((y - predicted) ** 2))
    total = float(np.sum((y - float(np.mean(y))) ** 2))
    r_squared = 1.0 - residual / total if total > 0 else 0.0
    if collective == "allreduce":
        steps = 2 * (world_size - 1)
        volume_factor = 2 * (world_size - 1) / world_size if world_size > 0 else 1.0
    elif collective == "allgather":
        steps = world_size - 1
        volume_factor = (world_size - 1) / world_size if world_size > 0 else 1.0
    else:
        raise ValueError(f"unknown collective {collective}")
    alpha = intercept / max(1, steps)
    beta = slope / max(1e-12, volume_factor)
    return float(alpha), float(beta), float(r_squared)


def _calibrate_one(
    runtime: AcceleratorRuntime,
    collective: str,
    max_rank_bytes: int,
) -> Mapping[str, Any]:
    sizes: List[int] = []
    times: List[float] = []
    for size_bytes in CALIBRATION_SIZES_BYTES:
        allocation = size_bytes if collective == "allreduce" else size_bytes * runtime.world_size
        if allocation > max_rank_bytes:
            continue
        numel = max(1, size_bytes // 4)
        value = torch.zeros(numel, dtype=torch.float32, device=runtime.device)
        outputs = [torch.empty_like(value) for _ in range(runtime.world_size)] if collective == "allgather" else None

        _distributed_barrier(runtime)
        if collective == "allreduce":
            dist.all_reduce(value)
        else:
            assert outputs is not None
            dist.all_gather(outputs, value)
        runtime.synchronize()

        iterations = 10 if size_bytes < 1_000_000 else 3
        _distributed_barrier(runtime)
        runtime.synchronize()
        started = time.perf_counter()
        for _ in range(iterations):
            if collective == "allreduce":
                dist.all_reduce(value)
            else:
                assert outputs is not None
                dist.all_gather(outputs, value)
        runtime.synchronize()
        elapsed = (time.perf_counter() - started) / iterations
        sizes.append(size_bytes)
        times.append(elapsed)
    if len(sizes) < 2:
        raise RuntimeError(
            f"calibration memory guard left only {len(sizes)} {collective} sizes; raise --calibration-max-rank-bytes"
        )
    alpha, beta, r_squared = fit_alpha_beta(sizes, times, runtime.world_size, collective)
    return {
        "alpha_s": alpha,
        "beta_s_per_byte": beta,
        "r2": r_squared,
        "sizes_bytes": sizes,
        "times_s": times,
        "allocation_guard_bytes": max_rank_bytes,
        "buffer_allocation": "preallocated_outside_timed_region",
    }


def calibrate_network(runtime: AcceleratorRuntime, args: argparse.Namespace) -> Mapping[str, Any]:
    if args.skip_calibration:
        return {
            "skipped": True,
            "reference": args.calibration_reference,
            "allreduce": None,
            "allgather": None,
        }
    return {
        "skipped": False,
        "reference": None,
        "allreduce": _calibrate_one(runtime, "allreduce", args.calibration_max_rank_bytes),
        "allgather": _calibrate_one(runtime, "allgather", args.calibration_max_rank_bytes),
    }


def _ddp_model(model: nn.Module, runtime: AcceleratorRuntime) -> DDP:
    return DDP(model, device_ids=[runtime.local_rank], output_device=runtime.local_rank)


def _gather_future(outputs: List[torch.Tensor], value: torch.Tensor, group: Any) -> Any:
    """all_gather as a future; falls back to a completed future if the backend
    does not expose futures for all_gather (recorded in HOOK_STATE)."""
    if HOOK_STATE.get("gather_futures") != "unsupported":
        try:
            fut = dist.all_gather(outputs, value, group=group, async_op=True).get_future()
            HOOK_STATE["gather_futures"] = "async"
            return fut
        except Exception as exc:  # pragma: no cover - backend dependent
            HOOK_STATE["gather_futures"] = "unsupported"
            HOOK_STATE["gather_futures_error"] = repr(exc)[:200]
    dist.all_gather(outputs, value, group=group)
    done = torch.futures.Future()
    done.set_result([outputs])
    return done


def _half_compress_hook(process_group, bucket):  # unannotated: DDP checks hook annotations
    """Port of torch.distributed.algorithms.ddp_comm_hooks.default_hooks.
    fp16_compress_hook with a selectable 16-bit dtype (HOOK_STATE["half_dtype"]).
    Algorithm unchanged: cast the bucket to 16 bits, divide by world size,
    all-reduce, copy back into the fp32 bucket."""
    group_to_use = process_group if process_group is not None else dist.group.WORLD
    world_size = group_to_use.size()
    dtype = getattr(torch, HOOK_STATE.get("half_dtype", "float16"))
    buffer = bucket.buffer()
    compressed = buffer.to(dtype).div_(world_size)
    fut = dist.all_reduce(compressed, group=group_to_use, async_op=True).get_future()

    def decompress(fut):
        value = fut.value()
        reduced = value[0] if isinstance(value, list) else value
        buffer.copy_(reduced)
        return buffer

    return fut.then(decompress)


def _pertensor_int8_hook(process_group, bucket):  # unannotated: DDP checks hook annotations
    """Port of torch.distributed.algorithms.ddp_comm_hooks.quantization_hooks.
    quantization_pertensor_hook with device-agnostic tensor placement (the
    upstream hook hardcodes .cuda). Algorithm unchanged: per-bucket min/max
    uint8 parameters, all-gather of the parameters, all-gather of the
    quantized buckets, per-source dequantization, mean over ranks."""
    group_to_use = process_group if process_group is not None else dist.group.WORLD
    world_size = group_to_use.size()
    tensor = bucket.buffer()
    device = tensor.device
    if "mode" not in HOOK_STATE:
        # oneCCL does not run nested future callbacks reliably; on that
        # backend the hook performs its collectives synchronously and the
        # provenance records it.
        backend = str(dist.get_backend(group_to_use)).lower()
        HOOK_STATE["mode"] = "sync" if "ccl" in backend or os.environ.get("RED_HOOK_SYNC") == "1" else "async"
        HOOK_STATE["backend"] = backend
    if HOOK_STATE["mode"] == "sync":
        zero = torch.zeros((), device=device, dtype=tensor.dtype)
        min_val = torch.minimum(tensor.min(), zero)
        max_val = torch.maximum(tensor.max(), zero)
        scale = (max_val - min_val) / 255.0
        scale = torch.where(scale > 0, scale, torch.full_like(scale, 1e-8))
        zero_point = torch.clamp(torch.round(-min_val / scale), 0.0, 255.0)
        s_and_z = torch.stack([scale, zero_point]).to(torch.float32)
        gathered_s_and_z = [torch.zeros(2, dtype=torch.float32, device=device) for _ in range(world_size)]
        dist.all_gather(gathered_s_and_z, s_and_z, group=group_to_use)
        quantized = torch.clamp(torch.round(tensor / scale) + zero_point, 0.0, 255.0).to(torch.uint8)
        all_ranks_quantized = [torch.zeros_like(quantized) for _ in range(world_size)]
        dist.all_gather(all_ranks_quantized, quantized, group=group_to_use)
        aggregated = torch.zeros_like(tensor, dtype=torch.float32)
        for source, source_quantized in enumerate(all_ranks_quantized):
            aggregated += (source_quantized.to(torch.float32) - gathered_s_and_z[source][1]) * gathered_s_and_z[source][0]
        done = torch.futures.Future()
        done.set_result(aggregated / world_size)
        return done
    zero = torch.zeros((), device=device, dtype=tensor.dtype)
    min_val = torch.minimum(tensor.min(), zero)
    max_val = torch.maximum(tensor.max(), zero)
    scale = (max_val - min_val) / 255.0
    scale = torch.where(scale > 0, scale, torch.full_like(scale, 1e-8))
    zero_point = torch.clamp(torch.round(-min_val / scale), 0.0, 255.0)
    s_and_z = torch.stack([scale, zero_point]).to(torch.float32)
    all_ranks_s_and_z = [torch.zeros(2, dtype=torch.float32, device=device) for _ in range(world_size)]
    fut = _gather_future(all_ranks_s_and_z, s_and_z, group_to_use)

    def quantize_and_allgather(fut: Any) -> Any:
        gathered_s_and_z = fut.wait()[0]
        HOOK_STATE["s_and_z"] = gathered_s_and_z
        quantized = torch.clamp(torch.round(tensor / scale) + zero_point, 0.0, 255.0).to(torch.uint8)
        all_ranks_quantized = [torch.zeros_like(quantized) for _ in range(world_size)]
        return _gather_future(all_ranks_quantized, quantized, group_to_use).wait()[0]

    def dequantize_and_aggregate(fut: Any) -> torch.Tensor:
        all_ranks_quantized = fut.wait()
        if isinstance(all_ranks_quantized, list) and len(all_ranks_quantized) == 1 \
                and isinstance(all_ranks_quantized[0], list):
            all_ranks_quantized = all_ranks_quantized[0]
        gathered_s_and_z = HOOK_STATE["s_and_z"]
        aggregated = torch.zeros_like(tensor, dtype=torch.float32)
        for source, quantized in enumerate(all_ranks_quantized):
            source_scale = gathered_s_and_z[source][0]
            source_zero = gathered_s_and_z[source][1]
            aggregated += (quantized.to(torch.float32) - source_zero) * source_scale
        return aggregated / world_size

    return fut.then(quantize_and_allgather).then(dequantize_and_aggregate)


def configure_model_for_mode(
    model: nn.Module,
    runtime: AcceleratorRuntime,
    args: argparse.Namespace,
) -> Tuple[nn.Module, Optional[DDP], Mapping[str, Any]]:
    if args.comm_mode not in DDP_MODES:
        return model, None, {"ddp": False}
    ddp_model = _ddp_model(model, runtime)
    details: Dict[str, Any] = {"ddp": True, "broadcast_buffers": True}
    if args.comm_mode == "powersgd":
        try:
            module = importlib.import_module(
                "torch.distributed.algorithms.ddp_comm_hooks.powerSGD_hook"
            )
            state_class = module.PowerSGDState
            hook = module.powerSGD_hook
        except Exception as exc:
            raise RuntimeError("PowerSGD was requested but the official PyTorch DDP hook is unavailable") from exc
        state_kwargs: Dict[str, Any] = {
            "process_group": dist.group.WORLD,
            "matrix_approximation_rank": args.powersgd_rank,
            "start_powerSGD_iter": args.powersgd_start,
            "use_error_feedback": args.powersgd_error_feedback,
            "warm_start": args.powersgd_warm_start,
            "random_seed": args.seed,
        }
        try:
            state = state_class(**state_kwargs)
        except TypeError as exc:
            if "random_seed" not in str(exc):
                raise
            state_kwargs.pop("random_seed")
            state = state_class(**state_kwargs)
        ddp_model.register_comm_hook(state, hook)
        details.update({"hook": "official_pytorch_powersgd", **state_kwargs})
        details["process_group"] = "WORLD"
    elif args.comm_mode == "ddp-fp16-hook":
        # 16-bit reducible hook: the official fp16/bf16 hooks are name-gated to
        # NCCL by torch 1.13 and oneCCL exposes no float16 ring all-reduce, so
        # this is the official five-line implementation with a selectable dtype:
        # bfloat16 on the ccl backend, float16 on CUDA. Same two-byte wire width.
        wanted = os.environ.get("RED_HOOK16_DTYPE") or ("bfloat16" if runtime.backend == "ccl" else "float16")
        HOOK_STATE["half_dtype"] = wanted
        ddp_model.register_comm_hook(dist.group.WORLD, _half_compress_hook)
        details.update({
            "hook": "pytorch_fp16_compress_hook_port_selectable_dtype",
            "dtype": wanted,
            "process_group": "WORLD",
            "hook_state": HOOK_STATE,
        })
    elif args.comm_mode == "ddp-int8-hook":
        ddp_model.register_comm_hook(dist.group.WORLD, _pertensor_int8_hook)
        details.update({
            "hook": "pytorch_quantization_pertensor_hook_device_agnostic_port",
            "process_group": "WORLD",
            "hook_state": HOOK_STATE,
        })
    return ddp_model, ddp_model, details


def warmup(
    run_model: nn.Module,
    base_model: nn.Module,
    ddp_model: Optional[DDP],
    get_data: Callable[[], Tuple[torch.Tensor, torch.Tensor]],
    loss_fn: nn.Module,
    optimizer: optim.Optimizer,
    runtime: AcceleratorRuntime,
    args: argparse.Namespace,
) -> float:
    backward_times: List[float] = []
    for _ in range(args.warmup_iters):
        optimizer.zero_grad(set_to_none=True)
        inputs, labels = get_data()
        if args.comm_mode == "powersgd":
            # DDP requires no_sync to cover the forward pass as well as backward;
            # otherwise the reducer is prepared during forward and this ceases to
            # be a compute-only baseline.
            assert ddp_model is not None
            with ddp_model.no_sync():
                output = run_model(inputs)
                loss = loss_fn(output, labels)
                _, elapsed = measure(runtime, loss.backward)
        else:
            output = run_model(inputs)
            loss = loss_fn(output, labels)
            _, elapsed = measure(runtime, loss.backward)
        backward_times.append(elapsed)
        _, _ = measure(runtime, optimizer.step)

    # Manual and PowerSGD no-sync warmups use rank-local synthetic inputs.  A
    # second broadcast makes the measured starting point identical on all ranks.
    broadcast_model(base_model, runtime)
    optimizer.zero_grad(set_to_none=True)
    _distributed_barrier(runtime)
    runtime.synchronize()
    if not backward_times:
        return 0.0
    tail = backward_times[-min(5, len(backward_times)):]
    return float(statistics.median(tail))


def _collect_topk(
    indices: torch.Tensor,
    values: torch.Tensor,
    runtime: AcceleratorRuntime,
) -> Tuple[List[torch.Tensor], List[torch.Tensor], List[int], int]:
    local_size = torch.tensor([indices.numel()], dtype=torch.int64, device=runtime.device)
    size_tensors = [torch.empty_like(local_size) for _ in range(runtime.world_size)]
    dist.all_gather(size_tensors, local_size)
    sizes = [int(value.item()) for value in size_tensors]
    maximum = max(sizes)
    index_buffer = torch.zeros(maximum, dtype=torch.int64, device=runtime.device)
    value_buffer = torch.zeros(maximum, dtype=torch.float32, device=runtime.device)
    index_buffer[: indices.numel()] = indices
    value_buffer[: values.numel()] = values
    index_outputs = [torch.empty_like(index_buffer) for _ in range(runtime.world_size)]
    value_outputs = [torch.empty_like(value_buffer) for _ in range(runtime.world_size)]
    dist.all_gather(index_outputs, index_buffer)
    dist.all_gather(value_outputs, value_buffer)
    return index_outputs, value_outputs, sizes, maximum


def _reconstruct_topk(
    index_outputs: Sequence[torch.Tensor],
    value_outputs: Sequence[torch.Tensor],
    sizes: Sequence[int],
    flat: torch.Tensor,
    world_size: int,
) -> torch.Tensor:
    reconstructed = torch.zeros_like(flat)
    for indices, values, size in zip(index_outputs, value_outputs, sizes):
        if size:
            reconstructed.index_add_(0, indices[:size], values[:size])
    reconstructed /= world_size
    return reconstructed


def _collect_gpu_quant(
    scale: torch.Tensor,
    encoded: torch.Tensor,
    runtime: AcceleratorRuntime,
) -> Tuple[List[torch.Tensor], List[torch.Tensor]]:
    scales = [torch.empty_like(scale) for _ in range(runtime.world_size)]
    payloads = [torch.empty_like(encoded) for _ in range(runtime.world_size)]
    dist.all_gather(scales, scale)
    dist.all_gather(payloads, encoded)
    return scales, payloads


def _collect_cpu_quant(
    payload: bytes,
    runtime: AcceleratorRuntime,
) -> Tuple[List[torch.Tensor], List[int], int]:
    length = torch.tensor([len(payload)], dtype=torch.int64, device=runtime.device)
    length_tensors = [torch.empty_like(length) for _ in range(runtime.world_size)]
    dist.all_gather(length_tensors, length)
    lengths = [int(value.item()) for value in length_tensors]
    maximum = max(lengths)
    buffer = torch.zeros(maximum, dtype=torch.uint8, device=runtime.device)
    source = torch.as_tensor(np.frombuffer(payload, dtype=np.uint8).copy(), dtype=torch.uint8, device=runtime.device)
    buffer[: len(payload)] = source
    outputs = [torch.empty_like(buffer) for _ in range(runtime.world_size)]
    dist.all_gather(outputs, buffer)
    return outputs, lengths, maximum


def _decode_cpu_quant(
    outputs: Sequence[torch.Tensor],
    lengths: Sequence[int],
    gradient_elements: int,
    device: torch.device,
) -> torch.Tensor:
    reconstructed = torch.zeros(gradient_elements, dtype=torch.float32, device=device)
    for output, length in zip(outputs, lengths):
        host = output[:length].detach().cpu().numpy().astype(np.uint8, copy=True).tobytes()
        reconstructed += cpu_dequantize(host, gradient_elements, device)
    reconstructed /= len(outputs)
    return reconstructed


